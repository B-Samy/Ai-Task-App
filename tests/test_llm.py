GOOD = '{"goal_summary":"g","tasks":[{"key":"a","title":"Read chapter one","estimate_minutes":60,"completion_criteria":"notes"},' \
       '{"key":"b","title":"Do the exercises","estimate_minutes":45,"prerequisites":["a"]}],"extra_field":1}'


class Fake(LLMProvider):
    name, model = "fake", "m"

    def __init__(self, replies):
        self.replies = list(replies)
        self.calls = 0

    def check(self):
        return ProviderStatus(True, "fake", "m", "ok")

    def _chat_once(self, messages, json_mode, timeout):
        self.calls += 1
        r = self.replies.pop(0)
        if isinstance(r, Exception):
            raise r
        return r


class ResponseStub:
    def __init__(self, status=200, body=None):
        self.status_code, self._b = status, body or {}

    def json(self):
        return self._b

    def raise_for_status(self):
        if self.status_code >= 400:
            raise requests.HTTPError()


class PlanParsing(unittest.TestCase):
    def test_valid_response_parses_and_ignores_unknown_fields(self):
        p = validate_plan(extract_json("Sure!\n```json\n" + GOOD + "\n```"), "llm:fake")
        self.assertEqual([t.key for t in p.tasks], ["a", "b"])
        self.assertEqual(p.source, "llm:fake")
        self.assertTrue(any("completion criteria" in w for w in p.warnings))

    def test_malformed_and_incomplete(self):
        for bad in ["", "no json here", '{"tasks": [', '{"tasks": [}']:
            with self.assertRaises(LLMBadResponse):
                extract_json(bad)
        with self.assertRaises(PlanValidationError):
            validate_plan({"tasks": []}, "x")
        with self.assertRaises(PlanValidationError):
            validate_plan({"goal_summary": "x"}, "x")

    def test_invalid_task_references_cycles_vague_duplicates(self):
        mk = lambda **k: {"key": "a", "title": "Specific task", "estimate_minutes": 30, **k}
        with self.assertRaises(PlanValidationError) as e:
            validate_plan({"tasks": [mk(prerequisites=["zzz"])]}, "x")
        self.assertIn("unknown prerequisite", str(e.exception))
        with self.assertRaises(PlanValidationError):
            validate_plan({"tasks": [mk(prerequisites=["a"])]}, "x")                     # self
        with self.assertRaises(PlanValidationError) as e:
            validate_plan({"tasks": [mk(prerequisites=["b"]), mk(key="b", title="Another task", prerequisites=["a"])]}, "x")
        self.assertIn("Circular", str(e.exception))
        with self.assertRaises(PlanValidationError):
            validate_plan({"tasks": [mk(title="stuff")]}, "x")                            # vague
        with self.assertRaises(PlanValidationError):
            validate_plan({"tasks": [mk(), mk(key="b")]}, "x")                            # duplicate title

    def test_past_and_invalid_deadlines_dropped_with_warning(self):
        p = validate_plan({"tasks": [{"key": "a", "title": "Write the report", "estimate_minutes": 30, "deadline": "2020-01-01"}]},
                          "x", today=date(2026, 1, 1))
        self.assertIsNone(p.tasks[0].deadline)

    def test_repair_attempt_then_success(self):
        f = Fake(["not json", GOOD])
        p = generate_plan_with_llm(f, "goal", "", max_retries=0)
        self.assertEqual(f.calls, 2)
        self.assertTrue(p.source.startswith("llm:"))

    def test_gives_up_after_one_repair(self):
        f = Fake(["bad", "still bad"])
        with self.assertRaises(LLMBadResponse):
            generate_plan_with_llm(f, "goal", "", max_retries=0)

    def test_fallbacks_are_labelled(self):
        t = template_plan("Learn guitar", 10, None)
        self.assertEqual(t.source, "fallback")
        self.assertIn("FALLBACK", t.warnings[0])
        m = manual_plan("G", ["Read the manual | 30", "Build the thing | 60 | after:1"])
        self.assertEqual(m.source, "manual")
        self.assertEqual(m.tasks[1].prerequisites, ["t1"])
        self.assertIn("not generated by an LLM", m.warnings[0])


class Providers(unittest.TestCase):
    def test_ollama_unreachable_gives_useful_message(self):
        sess = mock.Mock()
        sess.get.side_effect = requests.ConnectionError("boom")
        st = OllamaProvider(session=sess).check()
        self.assertFalse(st.ok)
        self.assertIn("Install/start Ollama", st.message)

    def test_ollama_missing_model(self):
        sess = mock.Mock()
        sess.get.return_value = ResponseStub(200, {"models": [{"name": "mistral:latest"}]})
        st = OllamaProvider(model="llama3.2", session=sess).check()
        self.assertFalse(st.ok)
        self.assertIn("ollama pull llama3.2", st.message)

    def test_ollama_ok_and_chat(self):
        sess = mock.Mock()
        sess.get.return_value = ResponseStub(200, {"models": [{"name": "llama3.2:latest"}]})
        sess.post.return_value = ResponseStub(200, {"message": {"content": "hi"}})
        p = OllamaProvider(session=sess)
        self.assertTrue(p.check().ok)
        self.assertEqual(p.chat([{"role": "user", "content": "x"}]), "hi")

    def test_ollama_404_is_model_missing_and_not_retried(self):
        from src.llm.base import LLMModelMissing
        sess = mock.Mock()
        sess.post.return_value = ResponseStub(404)
        with self.assertRaises(LLMModelMissing):
            OllamaProvider(session=sess).chat([{"role": "user", "content": "x"}], sleep=lambda s: None)
        self.assertEqual(sess.post.call_count, 1)

    def test_retries_are_bounded(self):
        f = Fake([LLMUnavailable("down")] * 5)
        with self.assertRaises(LLMUnavailable):
            f.chat([], max_retries=2, sleep=lambda s: None)
        self.assertEqual(f.calls, 3)

    def test_auth_error_not_retried(self):
        f = Fake([LLMAuthError("bad key"), "never"])
        with self.assertRaises(LLMAuthError):
            f.chat([], max_retries=3, sleep=lambda s: None)
        self.assertEqual(f.calls, 1)

    def test_hosted_errors(self):
        sess = mock.Mock()
        p = OpenAICompatProvider("https://x/v1", "m", api_key="sk-secret123456", session=sess)
        sess.post.return_value = ResponseStub(401)
        with self.assertRaises(LLMAuthError):
            p._chat_once([], False, 5)
        sess.post.return_value = ResponseStub(429)
        with self.assertRaises(LLMRateLimited):
            p._chat_once([], False, 5)
        sess.post.return_value = ResponseStub(200, {"unexpected": 1})
        with self.assertRaises(LLMBadResponse):
            p._chat_once([], False, 5)
        sess.post.side_effect = requests.Timeout()
        with self.assertRaises(LLMUnavailable):
            p._chat_once([], False, 5)

    def test_hosted_without_key(self):
        with mock.patch.dict("os.environ", {}, clear=True):
            p = OpenAICompatProvider("https://x/v1", "m")
        st = p.check()
        self.assertFalse(st.ok)
        self.assertIn(".env", st.message)

    def test_secrets_not_in_logs_or_messages(self):
        key = "sk-supersecretvalue123"
        sess = mock.Mock()
        sess.post.return_value = ResponseStub(401)
        p = OpenAICompatProvider("https://x/v1", "m", api_key=key, session=sess)
        with self.assertLogs("src.llm.base", level="WARNING") as cm:
            with self.assertRaises(LLMAuthError) as e:
                p.chat([], max_retries=1, sleep=lambda s: None)
            sess.post.return_value = ResponseStub(429)
            with self.assertRaises(LLMRateLimited):
                p.chat([], max_retries=1, sleep=lambda s: None)
        blob = "\n".join(cm.output) + str(e.exception)
        self.assertNotIn(key, blob)
        self.assertNotIn(key, redact(f"Authorization: Bearer {key}", key))
        self.assertNotIn(key, redact(f"api_key={key}"))
