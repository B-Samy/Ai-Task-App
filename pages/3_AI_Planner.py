import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import pandas as pd
import streamlit as st

from src.llm.base import LLMError
from src.llm.plan_schema import (Plan, PlanTask, PlanValidationError, generate_plan_with_llm, manual_plan,
                                 template_plan, validate_plan)
from src.ui.common import disclose_if_external, page, provider_or_none, safe

svc = page("AI Planner", "✨")
s = svc.settings
today = date.today()

tab_ai, tab_manual = st.tabs(["Plan with AI", "Manual / fallback planner"])

with tab_ai:
    if s.llm_provider == "none":
        st.info("No LLM provider is selected. Use the manual planner tab, or choose a provider in Settings.")
    else:
        st.caption(f"Provider: **{s.llm_provider}** ({s.ollama_model if s.llm_provider == 'ollama' else s.hosted_model}). "
                   "The model only proposes a plan. Scheduling constraints are enforced by deterministic code.")
        goal_text = st.text_area("Describe your goal", height=140, placeholder=
            "I want to learn machine learning in 90 days. I can study two hours every weekday and three hours on Sunday. I know Python and basic statistics.")
        constraints = st.text_input("Extra constraints (optional)", placeholder="e.g. no work on Saturdays, finish by 2027-02-01")
        ok_to_send = disclose_if_external(svc)
        if st.button("Generate plan", type="primary", disabled=not goal_text.strip() or not ok_to_send):
            prov = provider_or_none(svc)
            with st.spinner("Asking the model... local models can take a minute"):
                try:
                    plan = generate_plan_with_llm(prov, goal_text, constraints, timeout=max(s.llm_timeout_seconds, 90), today=today)
                    st.session_state.plan = plan
                    st.session_state.plan_goal = goal_text
                except PlanValidationError as exc:
                    st.error("The model's plan failed validation, so it was NOT used:")
                    for i in exc.issues:
                        st.write(f"- {i}")
                    st.info("Try again, simplify the goal, or use the manual planner.")
                except LLMError as exc:
                    st.error(f"LLM problem: {exc}")
                    st.info("You can still use the manual/fallback planner tab. Fallback plans are clearly labelled.")

with tab_manual:
    st.caption("This does not use an LLM. Enter one task per line: `title | minutes | after:1,2` (task numbers start at 1).")
    mt = st.text_input("Goal title", key="m_title")
    dl = st.date_input("Goal deadline (optional)", value=None, min_value=today, key="m_dl")
    lines = st.text_area("Tasks", height=160, key="m_lines", placeholder="Read chapter 1 | 60\nDo exercises | 45 | after:1")
    c1, c2 = st.columns(2)
    if c1.button("Build from my task list"):
        try:
            st.session_state.plan = manual_plan(mt or "Manual goal", lines.splitlines(), dl.isoformat() if dl else None)
            st.session_state.plan_goal = mt
        except PlanValidationError as exc:
            for i in exc.issues:
                st.error(i)
    hrs = c2.number_input("…or estimate total hours for a generic template", 1.0, 1000.0, 20.0)
    if c2.button("Generate generic fallback template"):
        st.session_state.plan = template_plan(mt or "My goal", hrs, dl.isoformat() if dl else None)
        st.session_state.plan_goal = mt

plan: Plan | None = st.session_state.get("plan")
if plan:
    st.divider()
    st.subheader("Review and edit the plan")
    badge = {"fallback": "⚠️ Fallback template (no LLM)", "manual": "✍️ Manual plan"}.get(plan.source, f"🤖 Generated by {plan.source}")
    st.markdown(f"**Source:** {badge}")
    for w in plan.warnings:
        st.warning(w)
    if plan.assumptions:
        with st.expander("Assumptions"):
            for a in plan.assumptions:
                st.write(f"- {a}")
    title = st.text_input("Goal title", value=(plan.goal_summary or st.session_state.get("plan_goal", ""))[:120])
    gc1, gc2, gc3 = st.columns(3)
    g_pr = gc1.slider("Goal priority", 1, 5, 3)
    g_dl = gc2.date_input("Goal deadline", value=None, min_value=today, key="goal_dl")
    g_cat = gc3.text_input("Category", "General")
    df = pd.DataFrame([{**t.__dict__, "prerequisites": ", ".join(t.prerequisites)} for t in plan.tasks])
    edited = st.data_editor(df, num_rows="dynamic", use_container_width=True, key="plan_editor",
                            column_config={"key": st.column_config.TextColumn("key", help="Referenced by prerequisites"),
                                           "priority": st.column_config.NumberColumn(min_value=1, max_value=5, step=1),
                                           "estimate_minutes": st.column_config.NumberColumn("minutes", min_value=5, max_value=6000, step=5)})
    c1, c2 = st.columns(2)
    if c1.button("✅ Approve and save", type="primary"):
        try:
            rows = []
            for r in edited.to_dict("records"):
                r["prerequisites"] = [p.strip() for p in str(r.get("prerequisites") or "").split(",") if p.strip()]
                r = {k: (None if (isinstance(v, float) and pd.isna(v)) else v) for k, v in r.items()}
                rows.append(r)
            checked = validate_plan({"goal_summary": title, "tasks": rows}, plan.source, today)
            if safe(svc.apply_plan, checked, None, {"title": title or "New goal", "priority": g_pr, "category": g_cat,
                                                      "deadline": g_dl.isoformat() if g_dl else None,
                                                      "description": plan.goal_summary}, success="Plan saved"):
                st.session_state.pop("plan", None)
                st.success("Saved. Open Schedule to build your calendar.")
        except PlanValidationError as exc:
            st.error("Fix these problems before saving:")
            for i in exc.issues:
                st.write(f"- {i}")
    if c2.button("Discard"):
        st.session_state.pop("plan", None)
        st.rerun()
